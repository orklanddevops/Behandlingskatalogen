INSERT INTO processor (processor_id, data, created_by, created_date, last_modified_by, last_modified_date)
SELECT gen_random_uuid(),
       jsonb_build_object('name', suppliers.name, 'contract', '', 'contractOwner', '',
                          'operationalContractManagers', '[]'::jsonb, 'note', '',
                          'outsideEU', NULL, 'transferGroundsOutsideEU', NULL,
                          'transferGroundsOutsideEUOther', '', 'countries', '[]'::jsonb),
       'Migration', now(), 'Migration', now()
FROM suppliers
WHERE NOT EXISTS (
    SELECT 1 FROM processor existing
    WHERE lower(btrim(existing.data ->> 'name')) = lower(btrim(suppliers.name))
);
